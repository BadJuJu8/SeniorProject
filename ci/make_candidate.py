#!/usr/bin/env python3
"""Build the CANDIDATE rule file for the shadow deploy (stage-candidate job).

The problem it solves: `detect` used to judge the attack with the rule already on
the manager, not the rule in the commit. So the commit's rule is staged NEXT TO
the live one, under its own ID, and the attack has to fire that ID before the real
local_rules.xml is deployed (see docs/LAB_JOURNAL.md, 2026-10-14 "ordering flaw").

For each manifest case that has a `candidate_rule_id`, this takes the commit's
version of the rule from rules/wazuh/local_rules.xml and rewrites it:

  * id            -> the candidate ID (100201 -> 110201)
  * parent        -> <if_sid>LIVE_ID</if_sid>, replacing if_group / if_sid /
                     decoded_as. As a child of the live rule the candidate can
                     never compete with it for an event: Wazuh raises one alert
                     per event and the deepest match wins.
  * description   -> prefixed with "[candidate]"
  * group         -> gains `candidate`

Everything else (the <field> conditions, level, mitre) is copied untouched, because
those are what the commit may have changed and what the attack must prove.

    python ci/make_candidate.py                       # every case with a candidate id
    python ci/make_candidate.py --technique kerberoasting
    python ci/make_candidate.py --out some/where.xml

Exit 0 = file written; 1 = nothing to build or the rules/manifest are inconsistent.
"""
from __future__ import annotations

import argparse
import copy
import sys
import xml.etree.ElementTree as ET
from pathlib import Path

import config

DEFAULT_OUT = config.REPO_ROOT / "build" / "local_rules_candidate.xml"

# Conditions that say "which rule/decoder am I chained under". The candidate gets
# exactly one of these: <if_sid> pointing at the live rule.
PARENT_TAGS = {"if_sid", "if_group", "if_level", "if_matched_sid", "if_matched_group",
               "decoded_as", "category"}

# Wazuh reserves 0-99999; custom rules live in 100000-120000.
CUSTOM_ID_RANGE = range(100000, 120001)


class CandidateError(Exception):
    pass


def make_candidate_rule(rule: ET.Element, live_id: str, candidate_id: str) -> ET.Element:
    """Return a copy of `rule` rewritten as a child of the live rule."""
    cand = copy.deepcopy(rule)
    cand.set("id", candidate_id)

    for child in list(cand):
        if child.tag in PARENT_TAGS:
            cand.remove(child)
    parent = ET.Element("if_sid")
    parent.text = live_id
    cand.insert(0, parent)

    desc = cand.find("description")
    if desc is not None:
        desc.text = f"[candidate] {(desc.text or '').strip()}"

    group = cand.find("group")
    if group is None:
        group = ET.SubElement(cand, "group")
        group.text = ""
    names = [g for g in (group.text or "").split(",") if g.strip()]
    if "candidate" not in names:
        names.append("candidate")
    group.text = ",".join(names) + ","
    return cand


def build(cases: list[dict], rules_path: Path = config.WAZUH_RULES_PATH) -> ET.Element:
    """Return the <group> element holding one candidate rule per case."""
    source = ET.parse(rules_path).getroot()
    by_id = {r.get("id"): r for r in source.iter("rule")}

    out = ET.Element("group", {"name": "windows,active_directory,detection_as_code,candidate,"})
    for case in cases:
        tech = case["technique"]
        live_id = str(case["expected_rule_id"])
        candidate_id = str(case["candidate_rule_id"])

        if live_id not in by_id:
            raise CandidateError(f"{tech}: rule {live_id} is not in {rules_path.name}")
        if candidate_id in by_id:
            raise CandidateError(
                f"{tech}: candidate id {candidate_id} is already used by a real rule")
        if not candidate_id.isdigit() or int(candidate_id) not in CUSTOM_ID_RANGE:
            raise CandidateError(
                f"{tech}: candidate id {candidate_id} is outside the custom range 100000-120000")
        if any(r.get("id") == candidate_id for r in out):
            raise CandidateError(f"{tech}: candidate id {candidate_id} is used twice")

        out.append(make_candidate_rule(by_id[live_id], live_id, candidate_id))
    return out


def render(group: ET.Element) -> str:
    ET.indent(group, space="  ")
    header = ("<!-- GENERATED by ci/make_candidate.py - do not edit, do not commit.\n"
              "     Staged next to local_rules.xml during CI and removed again on\n"
              "     promote or discard. -->\n")
    return header + ET.tostring(group, encoding="unicode") + "\n"


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__,
                                     formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--technique", help="only build the candidate for this manifest case")
    parser.add_argument("--out", type=Path, default=DEFAULT_OUT,
                        help=f"where to write the file (default {DEFAULT_OUT})")
    args = parser.parse_args()

    cases = config.manifest_cases()
    if args.technique:
        cases = [c for c in cases if c["technique"] == args.technique]
        if not cases:
            print(f"[FAIL] No manifest case for technique '{args.technique}'", file=sys.stderr)
            return 1
    cases = [c for c in cases if c.get("candidate_rule_id")]
    if not cases:
        print("[FAIL] No manifest case has a candidate_rule_id; nothing to stage.",
              file=sys.stderr)
        return 1

    try:
        group = build(cases)
    except (CandidateError, ET.ParseError) as exc:
        print(f"[FAIL] {exc}", file=sys.stderr)
        return 1

    args.out.parent.mkdir(parents=True, exist_ok=True)
    args.out.write_text(render(group), encoding="utf-8")
    for case in cases:
        print(f"[OK]   {case['technique']:<16} {case['expected_rule_id']} -> "
              f"candidate {case['candidate_rule_id']}")
    print(f"Wrote {args.out}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
